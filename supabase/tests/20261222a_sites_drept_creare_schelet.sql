CREATE OR REPLACE FUNCTION public.fn_site_name_to_cod_intern(p_name text)
 RETURNS text
 LANGUAGE plpgsql
 STABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v TEXT := p_name;
BEGIN
  -- 1. Scoate prefix "Gazpet -"
  v := REGEXP_REPLACE(v, '^Gazpet\s*[-–]\s*', '', 'i');
  -- 2. Scoate sufixe operator la final
  v := REGEXP_REPLACE(v, '\s*[-–]\s*(Transgaz|SNTGN|Depogaz|ADI.*)(\s+SA)?$', '', 'i');
  v := TRIM(v);
  -- 3. Înlocuiește diacritice ÎNAINTE de upper (TRANSLATE e case-sensitive)
  v := REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(
       REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(v,
    'ă','a'),'â','a'),'î','i'),'ș','s'),'ț','t'),
    'ş','s'),'ţ','t'),
    'Ă','A'),'Â','A'),'Î','I'),'Ș','S'),'Ț','T');
  -- 4. UPPER, apoi non-alfanumeric → _
  v := UPPER(v);
  v := REGEXP_REPLACE(v, '[^A-Z0-9]+', '_', 'g');
  -- 5. Curăță _ de la capete + consecutive
  v := REGEXP_REPLACE(TRIM(v, '_'), '_+', '_', 'g');
  RETURN LEFT(v, 50);
END;
$function$;
CREATE OR REPLACE FUNCTION public.fn_auto_create_executie_proiect()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_cod   TEXT;
  v_nume  TEXT;
  v_try   INTEGER := 0;
  v_cod_final TEXT;
BEGIN
  -- Nu crea pentru Sediu
  IF NEW.name ILIKE '%sediu%' THEN
    RETURN NEW;
  END IF;

  -- Dacă există deja proiect cu același site_id, nu dubla
  IF EXISTS (SELECT 1 FROM executie_proiecte WHERE site_id = NEW.id) THEN
    RETURN NEW;
  END IF;

  -- Generează cod_intern din nume
  v_cod  := fn_site_name_to_cod_intern(NEW.name);
  v_nume := UPPER(TRIM(
    REGEXP_REPLACE(NEW.name, '^Gazpet\s*[-–]\s*', '', 'i')
  ));

  -- Dacă cod colizionează, adaugă sufixul _2, _3 etc.
  v_cod_final := v_cod;
  WHILE EXISTS (SELECT 1 FROM executie_proiecte WHERE cod_intern = v_cod_final) LOOP
    v_try := v_try + 1;
    v_cod_final := v_cod || '_' || v_try;
  END LOOP;

  -- INSERT proiect nou — beneficiar NULL (utilizatorul completează la adăugarea contractului)
  INSERT INTO executie_proiecte (cod_intern, nume, beneficiar, site_id, activ)
  VALUES (v_cod_final, v_nume, NULL, NEW.id, true);

  RETURN NEW;
END;
$function$;
