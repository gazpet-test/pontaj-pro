-- Schelet minim „tip Supabase” pentru proba LOCALĂ (PGlite, în memorie) a migrării 20261223a_tichete_clarificari și a scriptului
-- scripts/tichete_clarificari_amprente.sql. NU e migrare și nu se rulează pe nicio bază reală (runner: scripts/pglite/test_tichete_clarificari_local.mjs).
-- Reproduce: rolurile (service_role cu BYPASSRLS), privilegiile implicite din public (ALL pentru anon / authenticated / service_role, ca la
-- Supabase), auth.uid() din cele două surse JWT, auth.users; tabelele tichete / tichete_comentarii / notifications cu coloanele și RLS-ul
-- verificate de coordonator pe producție (13.11.2026): comentarii — SELECT pentru orice cont logat, INSERT doar autor = auth.uid(), DELETE
-- autorul sau owner-ul, fără UPDATE; autor -> auth.users ON DELETE SET NULL; status-urile din CHECK-ul real.
-- Triggerele pe tichete: fn_tichete_notif_on_status_change e funcția REALĂ (runner-ul o extrage EXACT din 20261103d); celelalte sunt
-- ÎNLOCUITORI de test (corpurile reale nu sunt în repo: le arată pe producție scripts/tichete_clarificari_amprente.sql, secțiunea 1,
-- coloana definitie_lant, iar efectul real îl măsoară proba de pe clonă) — aleși ca să exercite închiderea L15: un trigger de istoric la
-- UPDATE (scrie în tichete_istoric, care are și el un trigger => lanț prin tabel), un trigger la INSERT cu SQL dinamic (în afara lanțului:
-- doar amprentat), numerotarea, un trigger BEFORE INSERT pe notifications.
CREATE ROLE anon NOLOGIN NOINHERIT;
CREATE ROLE authenticated NOLOGIN NOINHERIT;
CREATE ROLE service_role NOLOGIN NOINHERIT BYPASSRLS;
CREATE SCHEMA auth;
GRANT USAGE ON SCHEMA auth TO anon, authenticated, service_role;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $f$
  SELECT coalesce(nullif(current_setting('request.jwt.claim.sub', true), ''),
                  (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub'))::uuid
$f$;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated, service_role;
CREATE TABLE auth.users (id uuid PRIMARY KEY);
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;

CREATE TABLE public.profiles (id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE, name text, is_owner boolean DEFAULT false);
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY profiles_sel ON public.profiles FOR SELECT TO authenticated USING (auth.uid() IS NOT NULL);
CREATE FUNCTION public.fn_schelet_e_owner() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $f$
  SELECT EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.is_owner IS TRUE)
$f$;
REVOKE ALL ON FUNCTION public.fn_schelet_e_owner() FROM PUBLIC, anon;

CREATE TABLE public.logistica_service_parteneri (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nume text);
CREATE TABLE public.tichete (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numar_tichet text,
  departament text NOT NULL,
  subcategorie text,
  titlu text NOT NULL,
  descriere text,
  urgenta text DEFAULT 'normal',
  status text NOT NULL DEFAULT 'deschis' CHECK (status IN ('deschis', 'in_analiza', 'programat_service', 'in_service', 'reparat', 'atribuit',
                                                           'in_lucru', 'rezolvat', 'confirmat', 'inchis', 'respins')),
  deschis_de uuid REFERENCES public.profiles(id),
  persoana_responsabila uuid REFERENCES public.profiles(id),
  entitate_descriere text,
  service_partener_id bigint REFERENCES public.logistica_service_parteneri(id),
  firma_externa text,
  data_programare_service date,
  data_estimata_reparatie date,
  motiv_respingere text,
  descriere_interventie text,
  metadata jsonb DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);
ALTER TABLE public.tichete ENABLE ROW LEVEL SECURITY;
CREATE POLICY tichete_sel ON public.tichete FOR SELECT TO authenticated USING (auth.uid() IS NOT NULL);
CREATE POLICY tichete_ins ON public.tichete FOR INSERT TO authenticated WITH CHECK (deschis_de = auth.uid());
CREATE POLICY tichete_upd ON public.tichete FOR UPDATE TO authenticated USING (deschis_de = auth.uid() OR persoana_responsabila = auth.uid() OR public.fn_schelet_e_owner());

CREATE TABLE public.tichete_asignati (tichet_id bigint REFERENCES public.tichete(id) ON DELETE CASCADE, profile_id uuid REFERENCES public.profiles(id),
  PRIMARY KEY (tichet_id, profile_id));
CREATE TABLE public.tichete_istoric (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tichet_id bigint NOT NULL REFERENCES public.tichete(id) ON DELETE CASCADE,
  autor uuid, actiune text NOT NULL, detalii jsonb, created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE public.tichete_comentarii (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tichet_id bigint NOT NULL REFERENCES public.tichete(id) ON DELETE CASCADE,
  autor uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  text text NOT NULL,
  atasamente_paths text[],
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.tichete_comentarii ENABLE ROW LEVEL SECURITY;
CREATE POLICY comentarii_sel ON public.tichete_comentarii FOR SELECT TO authenticated USING (auth.uid() IS NOT NULL);
CREATE POLICY comentarii_ins ON public.tichete_comentarii FOR INSERT TO authenticated WITH CHECK (autor = auth.uid());
CREATE POLICY comentarii_del ON public.tichete_comentarii FOR DELETE TO authenticated USING (autor = auth.uid() OR public.fn_schelet_e_owner());

CREATE TABLE public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  type text, modul text, title text, message text, link_to text, read_at timestamptz, action_taken boolean,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
CREATE POLICY notifications_sel ON public.notifications FOR SELECT TO authenticated USING (profile_id = auth.uid());

-- ── triggerele (vezi antetul: unul REAL extras de runner, restul înlocuitori de test) ──
-- numerotarea (înlocuitor): BEFORE INSERT
CREATE FUNCTION public.fn_tichete_numar() RETURNS trigger LANGUAGE plpgsql SET search_path = public, pg_temp AS $f$
BEGIN NEW.numar_tichet := coalesce(NEW.numar_tichet, 'TKT-' || lpad(NEW.id::text, 4, '0')); RETURN NEW; END $f$;
CREATE TRIGGER trg_tichete_numar BEFORE INSERT ON public.tichete FOR EACH ROW EXECUTE FUNCTION public.fn_tichete_numar();
-- notificarea la tichet nou (înlocuitor cu SQL dinamic, ca originalul semnalat în docs/izometrie/E2A_INVENTAR_CITIRI.md): AFTER INSERT —
-- NU rulează la scrierile clarificărilor => doar amprentat, nu refuzat
CREATE FUNCTION public.fn_tichete_notif_on_insert() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $f$
DECLARE v_col text := 'is_owner';
BEGIN
  EXECUTE format('INSERT INTO public.notifications (profile_id, type, modul, title, message, link_to) SELECT id, %L, %L, %L, %L, %L FROM public.profiles WHERE %I = true',
                 'info', 'Tichete', 'Tichet nou ' || NEW.numar_tichet, left(NEW.titlu, 80), '/tichete?id=' || NEW.id, v_col);
  RETURN NEW;
END $f$;
CREATE TRIGGER trg_tichete_notif_insert AFTER INSERT ON public.tichete FOR EACH ROW EXECUTE FUNCTION public.fn_tichete_notif_on_insert();
-- istoricul (înlocuitor): AFTER UPDATE, scrie în tichete_istoric DOAR la schimbarea statusului; helper apelat după nume (callee tranzitiv,
-- adâncimea 1), care cheamă la rândul lui alt helper (adâncimea 2: o închidere pe un singur nivel nu-l vede)
CREATE FUNCTION public.fn_tichete_istoric_eticheta(p text) RETURNS text LANGUAGE sql IMMUTABLE SET search_path = public, pg_temp AS $f$
  SELECT coalesce(p, '-')
$f$;
CREATE FUNCTION public.fn_tichete_istoric_actiune(p_vechi text, p_nou text) RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path = public, pg_temp AS $f$
  SELECT jsonb_build_object('from', public.fn_tichete_istoric_eticheta(p_vechi), 'to', public.fn_tichete_istoric_eticheta(p_nou))
$f$;
CREATE FUNCTION public.fn_tichete_istoric_upd() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $f$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.tichete_istoric (tichet_id, autor, actiune, detalii)
    VALUES (NEW.id, auth.uid(), 'status_changed', public.fn_tichete_istoric_actiune(OLD.status, NEW.status));
  END IF;
  RETURN NEW;
END $f$;
CREATE TRIGGER trg_tichete_istoric_upd AFTER UPDATE ON public.tichete FOR EACH ROW EXECUTE FUNCTION public.fn_tichete_istoric_upd();
-- trigger pe tichete_istoric (înlocuitor): intră în lanț prin „INSERT INTO public.tichete_istoric” din corpul de mai sus
CREATE FUNCTION public.fn_tichete_istoric_marcheaza() RETURNS trigger LANGUAGE plpgsql SET search_path = public, pg_temp AS $f$
BEGIN NEW.created_at := coalesce(NEW.created_at, now()); RETURN NEW; END $f$;
CREATE TRIGGER trg_tichete_istoric_marcheaza BEFORE INSERT ON public.tichete_istoric FOR EACH ROW EXECUTE FUNCTION public.fn_tichete_istoric_marcheaza();
-- notifications (înlocuitor): BEFORE INSERT
CREATE FUNCTION public.fn_notifications_normalizeaza() RETURNS trigger LANGUAGE plpgsql SET search_path = public, pg_temp AS $f$
BEGIN NEW.modul := coalesce(NEW.modul, 'General'); RETURN NEW; END $f$;
CREATE TRIGGER trg_notifications_normalizeaza BEFORE INSERT ON public.notifications FOR EACH ROW EXECUTE FUNCTION public.fn_notifications_normalizeaza();
