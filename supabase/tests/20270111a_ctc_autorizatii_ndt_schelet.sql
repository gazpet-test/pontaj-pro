-- Se pune PESTE supabase/tests/20261222b_ctc_autorizatii_schelet.sql (rolurile tip Supabase, auth.uid(), profiles, user_module_access, HR),
-- înaintea migrărilor REALE 20260924_ofertare_parteneri_documente.sql și 20261222b_ctc_autorizatii_citire.sql.
-- ofertare_parteneri e creat direct în producție (nu e în migrări): coloanele folosite de ecranele Ofertare (OfertareParteneri.jsx,
-- OfertareCerinte.jsx), cu contact / observații ca proba să arate că lista CTC NU le întoarce. Politica de citire = cea a modulului Ofertare.
-- fn_are_acces_ofertare(): corpul din supabase/migrations/20260912_ofertare_acces_fara_parametru.sql (fără ALTER POLICY-urile de acolo).
CREATE TABLE public.ofertare_parteneri (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nume text NOT NULL, cui text, contact text, tip_relatie text NOT NULL DEFAULT 'subcontractant',
  observatii text, activ boolean NOT NULL DEFAULT true, abandonat boolean NOT NULL DEFAULT false, abandonat_motiv text
);
CREATE OR REPLACE FUNCTION public.fn_are_acces_ofertare()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $fn$
  SELECT auth.uid() IS NOT NULL AND (
    EXISTS (SELECT 1 FROM public.profiles pr WHERE pr.id = auth.uid() AND pr.is_owner)
    OR EXISTS (SELECT 1 FROM public.user_module_access uma
               WHERE uma.profile_id = auth.uid() AND uma.module = 'ofertare')
  );
$fn$;
REVOKE EXECUTE ON FUNCTION public.fn_are_acces_ofertare() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_are_acces_ofertare() FROM anon;
GRANT EXECUTE ON FUNCTION public.fn_are_acces_ofertare() TO authenticated, service_role;
ALTER TABLE public.ofertare_parteneri ENABLE ROW LEVEL SECURITY;
CREATE POLICY ofertare_parteneri_citire ON public.ofertare_parteneri FOR SELECT TO authenticated USING (public.fn_are_acces_ofertare());
CREATE POLICY ofertare_parteneri_scriere ON public.ofertare_parteneri FOR ALL TO authenticated USING (public.fn_are_acces_ofertare())
  WITH CHECK (public.fn_are_acces_ofertare());
