-- Schema FALSĂ, minimă, tip Supabase, pentru proba locală a migrării 20261225a (scripts/pglite/test_executie_uscare_local.mjs). NU e pentru producție.
-- Roluri ca în Supabase (service_role BYPASSRLS), auth.uid() din request.jwt.claim.sub / request.jwt.claims, drepturile implicite ALL pentru
-- rolurile API pe obiectele noi din public (deci migrarea TREBUIE să le retragă).
-- Tabelele de care depinde migrarea, cu coloanele citite: profiles, user_module_access, executie_proiecte, executie_acces_proiect (20261209a),
-- executie_probe_tronsoane (20261202a, forma minimă: cheia (id, proiect_id), starea), storage.buckets / storage.objects (cu RLS și o politică
-- a altui bucket). Funcțiile de drept NU sunt aici: proba le extrage EXACT din migrările lor (amprentele se verifică).
CREATE ROLE anon NOLOGIN NOINHERIT;
CREATE ROLE authenticated NOLOGIN NOINHERIT;
CREATE ROLE service_role NOLOGIN NOINHERIT BYPASSRLS;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(coalesce(nullif(current_setting('request.jwt.claim.sub', true), ''),
                         (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')), '')::uuid
$$;
GRANT USAGE ON SCHEMA auth, public TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;

CREATE TABLE public.profiles (id uuid PRIMARY KEY, name text, is_owner boolean NOT NULL DEFAULT false);
CREATE TABLE public.user_module_access (profile_id uuid NOT NULL REFERENCES public.profiles(id), module text NOT NULL, access_level text NOT NULL,
  PRIMARY KEY (profile_id, module));
CREATE TABLE public.executie_proiecte (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nume text NOT NULL);
CREATE TABLE public.executie_acces_proiect (
  profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  proiect_id bigint NOT NULL REFERENCES public.executie_proiecte(id) ON DELETE RESTRICT,
  nivel text NOT NULL DEFAULT 'editor',
  acordat_de uuid,
  acordat_la timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT executie_acces_proiect_pk PRIMARY KEY (profile_id, proiect_id),
  CONSTRAINT executie_acces_proiect_nivel_ck CHECK (nivel IN ('viewer', 'editor'))
);
CREATE TABLE public.executie_probe_tronsoane (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proiect_id bigint NOT NULL REFERENCES public.executie_proiecte(id),
  cod text NOT NULL,
  km_de_la_m integer NOT NULL,
  km_pana_la_m integer NOT NULL,
  stare text NOT NULL DEFAULT 'activ' CHECK (stare IN ('activ', 'anulat')),
  CONSTRAINT executie_probe_tronsoane_id_proiect_uq UNIQUE (id, proiect_id)
);
-- șantierele (sites: coloanele citite de RPC) și vremea curentă a șantierului (meteo_cache, scrisă de meteo-sync: curent.temp / .vreme / .la)
CREATE TABLE public.sites (id bigint PRIMARY KEY, name text NOT NULL, proiect_id bigint, lat numeric, lng numeric, active boolean NOT NULL DEFAULT true);
CREATE TABLE public.meteo_cache (site_id bigint PRIMARY KEY REFERENCES public.sites(id), curent jsonb, actualizat_la timestamptz, sursa text);
REVOKE ALL ON public.profiles, public.user_module_access, public.executie_proiecte, public.executie_acces_proiect, public.executie_probe_tronsoane,
  public.sites, public.meteo_cache FROM anon, authenticated, service_role;
GRANT SELECT ON public.executie_proiecte, public.executie_probe_tronsoane, public.sites, public.meteo_cache TO authenticated, service_role;

-- Storage (forma minimă: coloanele folosite; RLS ca în Supabase; drepturile rolurilor API ca în Supabase, filtrate de politici)
CREATE SCHEMA storage;
GRANT USAGE ON SCHEMA storage TO anon, authenticated, service_role;
CREATE TABLE storage.buckets (id text PRIMARY KEY, name text NOT NULL, public boolean DEFAULT false, file_size_limit bigint, allowed_mime_types text[]);
-- coloanele ca în Supabase (runda 3: owner_id, metadate, path_tokens generat), ca sonda migrării să le probeze pe toate
CREATE TABLE storage.objects (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  bucket_id text REFERENCES storage.buckets(id),
  name text,
  owner uuid,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  last_accessed_at timestamptz DEFAULT now(),
  metadata jsonb,
  path_tokens text[] GENERATED ALWAYS AS (string_to_array(name, '/')) STORED,
  version text,
  owner_id text,
  user_metadata jsonb,
  CONSTRAINT objects_bucket_name_uq UNIQUE (bucket_id, name)
);
CREATE FUNCTION storage.foldername(name text) RETURNS text[] LANGUAGE sql IMMUTABLE AS $$ SELECT (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'), 1) - 1] $$;
GRANT EXECUTE ON FUNCTION storage.foldername(text) TO anon, authenticated, service_role;
ALTER TABLE storage.buckets ENABLE ROW LEVEL SECURITY;
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON storage.buckets TO anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON storage.objects TO anon, authenticated, service_role;
CREATE POLICY buckets_citire ON storage.buckets FOR SELECT TO authenticated USING (true);
INSERT INTO storage.buckets (id, name, public) VALUES ('altul', 'altul', false);
-- politica altui bucket (permisivă): nu trebuie să deschidă nimic din bucket-ul nou
CREATE POLICY altul_tot ON storage.objects FOR ALL TO authenticated USING (bucket_id = 'altul') WITH CHECK (bucket_id = 'altul');
