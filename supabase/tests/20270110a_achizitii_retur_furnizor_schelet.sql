CREATE FUNCTION public.fn_cerere_rollup_status(p_cerere_id bigint) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public', 'pg_temp'
    AS $$
DECLARE
  v_cur text; v_dela uuid; v_proiect bigint; v_numar text;
  v_total int; v_uncovered int; v_min int; v_new text;
BEGIN
  SELECT status, deschis_de, proiect_id, numar_comanda
    INTO v_cur, v_dela, v_proiect, v_numar
  FROM public.comenzi WHERE id = p_cerere_id;
  IF NOT FOUND THEN RETURN; END IF;
  -- doar pe ciclul activ (nu atingem deschis/anulata/respinsa)
  IF v_cur NOT IN ('in_lucru','comandata','in_tranzit','ajunsa','finalizata') THEN RETURN; END IF;

  SELECT count(*) INTO v_total FROM public.comanda_linii WHERE comanda_id = p_cerere_id;
  IF v_total = 0 THEN RETURN; END IF;

  WITH line_stage AS (
    SELECT cl.id,
      COALESCE(MAX(CASE cf.status
        WHEN 'emisa' THEN 2 WHEN 'in_tranzit' THEN 3 WHEN 'ajunsa' THEN 4
        WHEN 'receptionata' THEN 5 WHEN 'in_stoc' THEN 5 ELSE 0 END), 0) AS stg
    FROM public.comanda_linii cl
    LEFT JOIN public.comenzi_furnizor_linii cfl ON cfl.comanda_linie_id = cl.id
    LEFT JOIN public.comenzi_furnizor cf ON cf.id = cfl.comanda_furnizor_id AND cf.status NOT IN ('anulata','respinsa')
    WHERE cl.comanda_id = p_cerere_id
    GROUP BY cl.id
  )
  SELECT count(*) FILTER (WHERE stg < 2), MIN(stg) INTO v_uncovered, v_min FROM line_stage;

  IF v_uncovered > 0 THEN
    v_new := 'in_lucru';
  ELSE
    v_new := CASE v_min WHEN 2 THEN 'comandata' WHEN 3 THEN 'in_tranzit'
                        WHEN 4 THEN 'ajunsa' WHEN 5 THEN 'finalizata' ELSE 'in_lucru' END;
  END IF;

  IF v_new IS DISTINCT FROM v_cur THEN
    UPDATE public.comenzi
      SET status = v_new,
          finalizata_la = CASE WHEN v_new='finalizata' THEN now() ELSE finalizata_la END
      WHERE id = p_cerere_id;
    IF v_dela IS NOT NULL THEN
      INSERT INTO public.notifications (profile_id, type, modul, title, message, link_to)
      VALUES (v_dela, 'cerere_status', 'Comercial',
        'Cerere '||COALESCE(v_numar,'')||' → '||v_new,
        'Statusul cererii tale interne s-a actualizat automat: '||v_new||'.',
        '/executie?proiect='||COALESCE(v_proiect::text,'')||'&tab=cereri');
    END IF;
  END IF;
END $$;
