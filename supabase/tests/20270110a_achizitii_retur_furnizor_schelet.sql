CREATE FUNCTION public.fn_cfl_automatch() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public', 'pg_temp'
    AS $$
DECLARE v_match bigint; v_cnt int; v_proiect bigint;
BEGIN
  IF NEW.comanda_linie_id IS NOT NULL THEN RETURN NEW; END IF;
  SELECT proiect_id INTO v_proiect FROM public.comenzi_furnizor WHERE id = NEW.comanda_furnizor_id;
  IF v_proiect IS NULL THEN RETURN NEW; END IF;
  SELECT MIN(cl.id), COUNT(*) INTO v_match, v_cnt
  FROM public.comanda_linii cl
  JOIN public.comenzi c ON c.id = cl.comanda_id
  WHERE c.proiect_id = v_proiect
    AND c.status NOT IN ('anulata','respinsa')
    AND LOWER(TRIM(cl.denumire)) = LOWER(TRIM(NEW.denumire))
    AND cl.cantitate = NEW.cantitate;
  IF v_cnt = 1 THEN NEW.comanda_linie_id := v_match; END IF;
  RETURN NEW;
END $$;
