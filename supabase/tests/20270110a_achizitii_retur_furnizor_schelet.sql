-- funcțiile de care depinde migrarea (corpul EXACT din dump) + drepturile lor de pe producție
CREATE FUNCTION public.fn_stocuri_aplica_miscare() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public', 'pg_temp'
    AS $$
DECLARE
  v_id bigint; v_cant_veche numeric; v_cost_vechi numeric; v_cost_nou numeric;
BEGIN
  SELECT id, cantitate, cost_mediu INTO v_id, v_cant_veche, v_cost_vechi
    FROM public.stocuri
   WHERE locatie_tip = NEW.locatie_tip
     AND locatie_id IS NOT DISTINCT FROM NEW.locatie_id
     AND material_denumire = NEW.material_denumire;

  IF v_id IS NULL THEN
    -- poziție nouă; dacă e intrare cu preț, cost_mediu = prețul
    INSERT INTO public.stocuri (locatie_tip, locatie_id, material_denumire, um, cantitate, cost_mediu)
    VALUES (NEW.locatie_tip, NEW.locatie_id, NEW.material_denumire, NEW.um, NEW.delta,
            CASE WHEN NEW.delta > 0 AND NEW.pret_unitar IS NOT NULL THEN NEW.pret_unitar ELSE NULL END);
  ELSE
    IF NEW.delta > 0 AND NEW.pret_unitar IS NOT NULL THEN
      -- intrare cu preț → WAC. Dacă nu știm costul vechi, luăm prețul nou (ultimul cunoscut).
      IF v_cost_vechi IS NULL OR v_cant_veche <= 0 THEN
        v_cost_nou := NEW.pret_unitar;
      ELSE
        v_cost_nou := (v_cant_veche * v_cost_vechi + NEW.delta * NEW.pret_unitar)
                      / NULLIF(v_cant_veche + NEW.delta, 0);
      END IF;
      UPDATE public.stocuri
         SET cantitate = cantitate + NEW.delta, cost_mediu = v_cost_nou,
             um = COALESCE(um, NEW.um), updated_at = now()
       WHERE id = v_id;
    ELSE
      -- ieșire sau intrare fără preț → cost_mediu neschimbat
      UPDATE public.stocuri
         SET cantitate = cantitate + NEW.delta, um = COALESCE(um, NEW.um), updated_at = now()
       WHERE id = v_id;
    END IF;
  END IF;
  RETURN NEW;
END $$;
