CREATE FUNCTION public.fn_stoc_ajustare(p_locatie_tip text, p_locatie_id bigint, p_material text, p_um text, p_delta numeric, p_motiv text) RETURNS numeric
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public', 'pg_temp'
    AS $$
DECLARE v_bal numeric;
BEGIN
  IF p_motiv IS NULL OR length(trim(p_motiv)) = 0 THEN RAISE EXCEPTION 'Motivul ajustării este obligatoriu'; END IF;
  IF p_delta = 0 THEN RAISE EXCEPTION 'Delta nu poate fi 0'; END IF;
  INSERT INTO public.stocuri_miscari (locatie_tip, locatie_id, material_denumire, um, delta, tip, motiv, ref_tip, created_by)
  VALUES (p_locatie_tip, p_locatie_id, p_material, p_um, p_delta,
          CASE WHEN p_delta > 0 THEN 'ajustare_plus' ELSE 'ajustare_minus' END, p_motiv, 'manual', auth.uid());
  SELECT cantitate INTO v_bal FROM public.stocuri
   WHERE locatie_tip=p_locatie_tip AND locatie_id IS NOT DISTINCT FROM p_locatie_id AND material_denumire=p_material;
  RETURN v_bal;
END $$;
