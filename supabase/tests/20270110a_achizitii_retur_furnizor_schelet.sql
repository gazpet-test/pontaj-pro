CREATE FUNCTION public.fn_cf_sync_cereri() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public', 'pg_temp'
    AS $$
DECLARE v_cid bigint;
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    FOR v_cid IN
      SELECT DISTINCT cl.comanda_id
      FROM public.comenzi_furnizor_linii cfl
      JOIN public.comanda_linii cl ON cl.id = cfl.comanda_linie_id
      WHERE cfl.comanda_furnizor_id = NEW.id AND cl.comanda_id IS NOT NULL
    LOOP
      PERFORM public.fn_cerere_rollup_status(v_cid);
    END LOOP;
  END IF;
  RETURN NEW;
END $$;
