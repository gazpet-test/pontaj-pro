CREATE FUNCTION public.fn_transfer_executa(p_de_la_tip text, p_de_la_id bigint, p_la_tip text, p_la_id bigint, p_obs text, p_linii jsonb) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public', 'pg_temp'
    AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_transfer bigint; v_linie jsonb; v_den text; v_um text; v_qty numeric; v_disp numeric; v_cost numeric;
BEGIN
  IF p_de_la_tip IS NULL OR p_la_tip IS NULL THEN RAISE EXCEPTION 'Locație sursă/destinație lipsă'; END IF;
  IF p_de_la_tip = p_la_tip AND COALESCE(p_de_la_id, -1) = COALESCE(p_la_id, -1) THEN
    RAISE EXCEPTION 'Sursa și destinația sunt identice'; END IF;
  IF p_linii IS NULL OR jsonb_array_length(p_linii) = 0 THEN RAISE EXCEPTION 'Niciun material în transfer'; END IF;

  FOR v_linie IN SELECT * FROM jsonb_array_elements(p_linii) LOOP
    v_den := btrim(v_linie->>'material_denumire');
    v_qty := COALESCE((v_linie->>'cantitate')::numeric, 0);
    IF v_den = '' OR v_den IS NULL THEN RAISE EXCEPTION 'Material fără denumire'; END IF;
    IF v_qty <= 0 THEN RAISE EXCEPTION 'Cantitate invalidă pentru %', v_den; END IF;
    SELECT cantitate INTO v_disp FROM public.stocuri
      WHERE locatie_tip = p_de_la_tip AND (locatie_id IS NOT DISTINCT FROM p_de_la_id)
        AND lower(material_denumire) = lower(v_den) LIMIT 1;
    IF v_disp IS NULL OR v_disp < v_qty THEN
      RAISE EXCEPTION 'Stoc insuficient pentru "%": disponibil %, cerut %', v_den, COALESCE(v_disp, 0), v_qty;
    END IF;
  END LOOP;

  INSERT INTO public.transferuri_interne
    (de_la_locatie_tip, de_la_locatie_id, la_locatie_tip, la_locatie_id,
     status, data_plecare, data_sosire, observatii, created_by)
  VALUES
    (p_de_la_tip, p_de_la_id, p_la_tip, p_la_id, 'livrat', CURRENT_DATE, CURRENT_DATE,
     NULLIF(btrim(p_obs), ''), v_uid)
  RETURNING id INTO v_transfer;

  FOR v_linie IN SELECT * FROM jsonb_array_elements(p_linii) LOOP
    v_den := btrim(v_linie->>'material_denumire');
    v_um  := NULLIF(btrim(COALESCE(v_linie->>'um','')), '');
    v_qty := (v_linie->>'cantitate')::numeric;

    -- cost mediu al sursei (pentru propagare valoare la destinație)
    SELECT cost_mediu INTO v_cost FROM public.stocuri
      WHERE locatie_tip = p_de_la_tip AND (locatie_id IS NOT DISTINCT FROM p_de_la_id)
        AND lower(material_denumire) = lower(v_den) LIMIT 1;

    INSERT INTO public.transferuri_linii (transfer_id, material_denumire, um, cantitate)
    VALUES (v_transfer, v_den, v_um, v_qty);

    INSERT INTO public.stocuri_miscari
      (locatie_tip, locatie_id, material_denumire, um, delta, tip, motiv, ref_tip, ref_id, created_by)
    VALUES
      (p_de_la_tip, p_de_la_id, v_den, v_um, -v_qty, 'transfer_out',
       'Transfer #'||v_transfer, 'transfer', v_transfer, v_uid);

    -- transfer_in cu cost propagat (pret_unitar = cost sursă) → WAC corect la destinație
    INSERT INTO public.stocuri_miscari
      (locatie_tip, locatie_id, material_denumire, um, delta, tip, motiv, ref_tip, ref_id, created_by, pret_unitar)
    VALUES
      (p_la_tip, p_la_id, v_den, v_um, v_qty, 'transfer_in',
       'Transfer #'||v_transfer, 'transfer', v_transfer, v_uid, v_cost);
  END LOOP;

  RETURN v_transfer;
END $$;
