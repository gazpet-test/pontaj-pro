CREATE FUNCTION public.fn_consum_executa(p_locatie_tip text, p_locatie_id bigint, p_predat text, p_primit text, p_obs text, p_linii jsonb) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public', 'pg_temp'
    AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_consum bigint; v_linie jsonb; v_den text; v_um text; v_qty numeric; v_disp numeric;
BEGIN
  IF v_uid IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.profiles WHERE id=v_uid AND (is_owner OR can_manage_stoc)) THEN
    RAISE EXCEPTION 'Nu ai dreptul să înregistrezi consum (necesită gestiune stoc).';
  END IF;
  IF p_locatie_tip IS NULL THEN RAISE EXCEPTION 'Locație lipsă'; END IF;
  IF p_linii IS NULL OR jsonb_array_length(p_linii)=0 THEN RAISE EXCEPTION 'Niciun material în consum'; END IF;

  FOR v_linie IN SELECT * FROM jsonb_array_elements(p_linii) LOOP
    v_den := btrim(v_linie->>'material_denumire');
    v_qty := COALESCE((v_linie->>'cantitate')::numeric, 0);
    IF v_den = '' OR v_den IS NULL THEN RAISE EXCEPTION 'Material fără denumire'; END IF;
    IF v_qty <= 0 THEN RAISE EXCEPTION 'Cantitate invalidă pentru %', v_den; END IF;
    SELECT cantitate INTO v_disp FROM public.stocuri
      WHERE locatie_tip = p_locatie_tip AND (locatie_id IS NOT DISTINCT FROM p_locatie_id)
        AND lower(material_denumire) = lower(v_den) LIMIT 1;
    IF v_disp IS NULL OR v_disp < v_qty THEN
      RAISE EXCEPTION 'Stoc insuficient pentru "%": disponibil %, cerut %', v_den, COALESCE(v_disp,0), v_qty;
    END IF;
  END LOOP;

  INSERT INTO public.consumuri_proiect (locatie_tip, locatie_id, predat_de, primit_de, observatii, created_by)
  VALUES (p_locatie_tip, p_locatie_id, NULLIF(btrim(p_predat),''), NULLIF(btrim(p_primit),''), NULLIF(btrim(p_obs),''), v_uid)
  RETURNING id INTO v_consum;

  FOR v_linie IN SELECT * FROM jsonb_array_elements(p_linii) LOOP
    v_den := btrim(v_linie->>'material_denumire');
    v_um  := NULLIF(btrim(COALESCE(v_linie->>'um','')), '');
    v_qty := (v_linie->>'cantitate')::numeric;
    INSERT INTO public.consumuri_proiect_linii (consum_id, material_denumire, um, cantitate)
    VALUES (v_consum, v_den, v_um, v_qty);
    INSERT INTO public.stocuri_miscari
      (locatie_tip, locatie_id, material_denumire, um, delta, tip, motiv, ref_tip, ref_id, created_by)
    VALUES
      (p_locatie_tip, p_locatie_id, v_den, v_um, -v_qty, 'consum_proiect', 'Consum #'||v_consum, 'consum', v_consum, v_uid);
  END LOOP;

  RETURN v_consum;
END $$;
