CREATE FUNCTION public.fn_cfl_sync_cereri() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public', 'pg_temp'
    AS $$
DECLARE v_cid bigint;
BEGIN
  IF TG_OP IN ('DELETE','UPDATE') AND OLD.comanda_linie_id IS NOT NULL THEN
    SELECT comanda_id INTO v_cid FROM public.comanda_linii WHERE id = OLD.comanda_linie_id;
    IF v_cid IS NOT NULL THEN PERFORM public.fn_cerere_rollup_status(v_cid); END IF;
  END IF;
  IF TG_OP IN ('INSERT','UPDATE') AND NEW.comanda_linie_id IS NOT NULL
     AND (TG_OP = 'INSERT' OR NEW.comanda_linie_id IS DISTINCT FROM OLD.comanda_linie_id) THEN
    SELECT comanda_id INTO v_cid FROM public.comanda_linii WHERE id = NEW.comanda_linie_id;
    IF v_cid IS NOT NULL THEN PERFORM public.fn_cerere_rollup_status(v_cid); END IF;
  END IF;
  RETURN COALESCE(NEW, OLD);
END $$;
