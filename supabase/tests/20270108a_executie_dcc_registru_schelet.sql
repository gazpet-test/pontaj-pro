-- Schema FALSĂ, minimă, tip Supabase, pentru proba locală a migrării 20270108a (scripts/pglite/test_executie_dcc_registru_local.mjs). NU e pentru
-- producție. Roluri ca în Supabase (service_role BYPASSRLS; authenticator NOINHERIT, membru în anon / authenticated / service_role — calea
-- API: session_user = authenticator), auth.uid() din request.jwt.claim.sub apoi request.jwt.claims, drepturile implicite ALL pentru rolurile
-- API pe obiectele noi din public (deci migrarea TREBUIE să le retragă).
-- Tabelele de care depinde migrarea, cu coloanele citite: profiles (id, is_owner, employee_id), user_module_access, executie_proiecte (id, …),
-- executie_acces_proiect (20261209a). Funcțiile de drept pe proiect NU sunt aici: proba le extrage EXACT din 20261209a (amprentele se verifică).
-- Istoricul runnerului (supabase_migrations.schema_migrations) are forma din testele runnerului (scripts/test_livrare_l15_v2.sh).
CREATE ROLE anon NOLOGIN NOINHERIT;
CREATE ROLE authenticated NOLOGIN NOINHERIT;
CREATE ROLE service_role NOLOGIN NOINHERIT BYPASSRLS;
CREATE ROLE authenticator NOINHERIT;
GRANT anon, authenticated, service_role TO authenticator;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(coalesce(nullif(current_setting('request.jwt.claim.sub', true), ''),
                         (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')), '')::uuid
$$;
GRANT USAGE ON SCHEMA auth, public TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;

CREATE TABLE public.profiles (id uuid PRIMARY KEY, name text, is_owner boolean NOT NULL DEFAULT false, employee_id integer);
CREATE TABLE public.user_module_access (profile_id uuid NOT NULL REFERENCES public.profiles(id), module text NOT NULL, access_level text NOT NULL,
  PRIMARY KEY (profile_id, module));
CREATE TABLE public.app_modules (key text PRIMARY KEY, parent_key text, name text NOT NULL, icon text, description text,
  is_active boolean NOT NULL DEFAULT true, show_on_homepage boolean NOT NULL DEFAULT true);
CREATE TABLE public.executie_proiecte (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cod_intern text, nume text NOT NULL,
  activ boolean NOT NULL DEFAULT true);
CREATE TABLE public.executie_acces_proiect (
  profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  proiect_id bigint NOT NULL REFERENCES public.executie_proiecte(id) ON DELETE RESTRICT,
  nivel text NOT NULL DEFAULT 'editor',
  acordat_de uuid,
  acordat_la timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT executie_acces_proiect_pk PRIMARY KEY (profile_id, proiect_id),
  CONSTRAINT executie_acces_proiect_nivel_ck CHECK (nivel IN ('viewer', 'editor'))
);
REVOKE ALL ON public.profiles, public.user_module_access, public.app_modules, public.executie_proiecte, public.executie_acces_proiect
  FROM anon, authenticated, service_role;
GRANT SELECT ON public.executie_proiecte TO authenticated, service_role;
-- ca în producție: executie_proiecte se citește doar autentificat + restricția pe proiect (20261209a, pusă de probă)
ALTER TABLE public.executie_proiecte ENABLE ROW LEVEL SECURITY;
CREATE POLICY executie_proiecte_citire ON public.executie_proiecte FOR SELECT TO authenticated USING (auth.uid() IS NOT NULL);
CREATE SCHEMA supabase_migrations;
CREATE TABLE supabase_migrations.schema_migrations (version text PRIMARY KEY, statements text[], name text);
