-- Schelet LOCAL (PGlite / PG de unică folosință) pentru 20261231a (Magazie → Echipamente: referința intenției). NU se rulează pe producție.
-- Reproduce DOAR ce citește / atinge migrarea: rolurile Supabase (service_role BYPASSRLS), privilegiile implicite periculoase (ALL / EXECUTE pe
-- obiecte noi: migrarea trebuie să le scoată de pe funcția nouă), auth.uid() (textul live: claim-ul request.jwt.claim.sub) și magazie_echipamente
-- cu forma „moștenită” din scripts/pg/test_magazie_eip.mjs (citire pentru oricine, scriere pentru orice cont logat), indexul unic EIP din
-- 20261110a (alt index unic pe tabel, ca ON CONFLICT să aibă de ales) și vederea v_magazie_echipamente (security_invoker) din care citește ecranul.
DO $r$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN CREATE ROLE anon NOLOGIN NOINHERIT; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN CREATE ROLE authenticated NOLOGIN NOINHERIT; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN CREATE ROLE service_role NOLOGIN NOINHERIT BYPASSRLS; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'supabase_auth_admin') THEN CREATE ROLE supabase_auth_admin NOLOGIN; END IF;
END $r$;
CREATE SCHEMA auth;
GRANT USAGE ON SCHEMA public, auth TO anon, authenticated, service_role;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT EXECUTE ON FUNCTIONS TO anon, authenticated, service_role;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $function$
  select coalesce(nullif(current_setting('request.jwt.claim.sub', true), ''), (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub'))::uuid
$function$;
ALTER FUNCTION auth.uid() OWNER TO supabase_auth_admin;

CREATE TABLE public.magazie_echipamente (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, denumire text NOT NULL, categorie text NOT NULL, este_eip boolean DEFAULT false,
  um text NOT NULL, serie text, cantitate_total numeric DEFAULT 0, stare text NOT NULL CHECK (stare IN ('functional', 'defect', 'casat')),
  comanda_sursa_id bigint, observatii text, activ boolean DEFAULT true, created_at timestamptz DEFAULT now(), created_by uuid,
  articol_id bigint, marime text);
CREATE UNIQUE INDEX eip_stoc_articol_marime_uq ON public.magazie_echipamente (articol_id, (coalesce(marime, ''))) WHERE activ AND articol_id IS NOT NULL;
ALTER TABLE public.magazie_echipamente ENABLE ROW LEVEL SECURITY;
CREATE POLICY legacy_select ON public.magazie_echipamente FOR SELECT USING (true);
CREATE POLICY legacy_write ON public.magazie_echipamente FOR ALL TO authenticated USING (auth.uid() IS NOT NULL) WITH CHECK (auth.uid() IS NOT NULL);
REVOKE ALL ON public.magazie_echipamente FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.magazie_echipamente TO authenticated;
REVOKE ALL ON SEQUENCE public.magazie_echipamente_id_seq FROM anon;
-- vederea din care citește lista ecranului (coloanele fixate la creare: coloana nouă NU apare în ea, ca pe live)
CREATE VIEW public.v_magazie_echipamente WITH (security_invoker = on) AS SELECT e.* FROM public.magazie_echipamente e;
REVOKE ALL ON public.v_magazie_echipamente FROM PUBLIC, anon;
