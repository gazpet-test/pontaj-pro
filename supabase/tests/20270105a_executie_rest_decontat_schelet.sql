-- „accesul general la Execuție” (owner sau modulul 'executie'), ca politicile de azi; service_role sare peste RLS
CREATE FUNCTION public.fx_executie_general() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER AS $f$
  SELECT auth.uid() IS NOT NULL AND (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.is_owner)
    OR EXISTS (SELECT 1 FROM public.user_module_access u WHERE u.profile_id = auth.uid() AND u.module = 'executie'))
$f$;
