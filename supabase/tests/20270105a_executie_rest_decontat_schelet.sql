DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['profiles', 'user_module_access', 'employees', 'executie_proiecte', 'sites', 'profile_sites'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (auth.uid() IS NOT NULL) WITH CHECK (auth.uid() IS NOT NULL)', t || '_autentificat', t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY['executie_acte_aditionale', 'executie_situatii_plata', 'proiect_unitati'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (public.fx_executie_general()) WITH CHECK (public.fx_executie_general())', t || '_executie', t);
  END LOOP;
END $rls$;
