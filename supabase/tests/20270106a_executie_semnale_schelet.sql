-- Schema FALSĂ, minimă, tip Supabase, pentru proba locală a migrării 20270106a (scripts/pglite/test_executie_semnale_local.mjs). NU e pentru producție.
-- Roluri ca în Supabase (service_role BYPASSRLS), auth.uid() din request.jwt.claim.sub / request.jwt.claims, drepturile implicite ALL pentru
-- rolurile API pe obiectele noi din public (deci migrarea TREBUIE să le retragă).
-- Tabelele de care depinde migrarea, cu coloanele citite: profiles (cu employee_id), user_module_access, employees, executie_proiecte (cu
-- mp_employee_id, cod_intern, nume), executie_acces_proiect (20261209a), sites / profile_sites (șeful de șantier). RLS „autentificat” pe
-- executie_proiecte, ca în producție (vederea security_invoker o moștenește). Funcțiile de drept NU sunt aici: proba le extrage EXACT din 20261209a
-- (amprentele se verifică).
CREATE ROLE anon NOLOGIN NOINHERIT;
CREATE ROLE authenticated NOLOGIN NOINHERIT;
CREATE ROLE service_role NOLOGIN NOINHERIT BYPASSRLS;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(coalesce(nullif(current_setting('request.jwt.claim.sub', true), ''),
                         (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')), '')::uuid
$$;
GRANT USAGE ON SCHEMA auth, public TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;

CREATE TABLE public.employees (id serial PRIMARY KEY, name text NOT NULL, active boolean NOT NULL DEFAULT true);
CREATE TABLE public.profiles (id uuid PRIMARY KEY, name text, is_owner boolean NOT NULL DEFAULT false, employee_id integer REFERENCES public.employees(id));
CREATE TABLE public.user_module_access (profile_id uuid NOT NULL REFERENCES public.profiles(id), module text NOT NULL, access_level text NOT NULL,
  PRIMARY KEY (profile_id, module));
CREATE TABLE public.executie_proiecte (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cod_intern text, nume text NOT NULL,
  mp_employee_id integer REFERENCES public.employees(id), activ boolean NOT NULL DEFAULT true);
CREATE TABLE public.executie_acces_proiect (
  profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  proiect_id bigint NOT NULL REFERENCES public.executie_proiecte(id) ON DELETE RESTRICT,
  nivel text NOT NULL DEFAULT 'editor',
  acordat_de uuid,
  acordat_la timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT executie_acces_proiect_pk PRIMARY KEY (profile_id, proiect_id),
  CONSTRAINT executie_acces_proiect_nivel_ck CHECK (nivel IN ('viewer', 'editor'))
);
CREATE TABLE public.sites (id bigint PRIMARY KEY, name text NOT NULL, proiect_id bigint REFERENCES public.executie_proiecte(id));
CREATE TABLE public.profile_sites (profile_id uuid NOT NULL REFERENCES public.profiles(id), site_id bigint NOT NULL REFERENCES public.sites(id),
  valid_until date, PRIMARY KEY (profile_id, site_id));
REVOKE ALL ON public.profiles, public.user_module_access, public.employees, public.executie_proiecte, public.executie_acces_proiect, public.sites, public.profile_sites
  FROM anon, authenticated, service_role;
GRANT SELECT ON public.executie_proiecte, public.employees, public.sites TO authenticated, service_role;
-- ca în producție: executie_proiecte se citește doar autentificat (politica din 30.09.2026) + restricția pe proiect (20261209a, pusă de probă)
ALTER TABLE public.executie_proiecte ENABLE ROW LEVEL SECURITY;
CREATE POLICY executie_proiecte_citire ON public.executie_proiecte FOR SELECT TO authenticated USING (auth.uid() IS NOT NULL);
