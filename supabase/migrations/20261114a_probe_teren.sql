-- Comparatie la nivel de proba; nu repartizam bazinul pe utilaje.
CREATE FUNCTION public.probe_teren_bazin(p_calc_id bigint) RETURNS numeric
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public','pg_temp'
AS $pt_bazin_20261114a$
 SELECT CASE WHEN c.ora_stop IS NOT NULL THEN coalesce((
   SELECT sum(a.cantitate_litri) FROM public.logistica_alimentari a
   -- Daca sursa are doar data, comparatia poate avea numai precizie de zi locala.
   WHERE CASE WHEN pg_typeof(a.data_alimentare)='date'::regtype THEN
       a.data_alimentare::date BETWEEN (c.ora_start AT TIME ZONE 'Europe/Bucharest')::date
         AND (c.ora_stop AT TIME ZONE 'Europe/Bucharest')::date
     ELSE a.data_alimentare::timestamptz BETWEEN c.ora_start AND c.ora_stop END
     AND a.rezervor_id IS NOT NULL
     AND EXISTS(SELECT 1 FROM public.probe_exec_utilaje e WHERE e.calc_id=c.id AND e.active_id=a.active_id)
 ),0) END FROM public.probe_calcule c WHERE c.id=p_calc_id AND public.probe_teren_drept(false);
$pt_bazin_20261114a$;

