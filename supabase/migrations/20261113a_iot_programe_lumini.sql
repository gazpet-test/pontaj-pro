CREATE TABLE public.iot_lumini (
  dispozitiv_id integer PRIMARY KEY REFERENCES public.iot_dispozitive(id),
  rol text NOT NULL CHECK (rol IN ('exterior','interior','mixt')),
  activ boolean NOT NULL DEFAULT true, creat_la timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.iot_program_lumini (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nume text NOT NULL CHECK (length(trim(nume)) BETWEEN 1 AND 120),
  tip text NOT NULL CHECK (tip IN ('solar','orar','simulare_prezenta')),
  dispozitive integer[] NOT NULL CHECK (cardinality(dispozitive) BETWEEN 1 AND 6),
  parametri jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(parametri)='object'),
  activ boolean NOT NULL DEFAULT false,
  creat_de uuid NOT NULL REFERENCES public.profiles(id),
  aprobat_de uuid REFERENCES public.profiles(id), aprobat_la timestamptz,
  creat_la timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT activ OR (aprobat_de IS NOT NULL AND aprobat_la IS NOT NULL))
);
CREATE TABLE public.iot_lumini_jurnal (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dispozitiv_id integer NOT NULL REFERENCES public.iot_lumini(dispozitiv_id),
  comanda boolean NOT NULL, sursa text NOT NULL CHECK (sursa IN ('manual','program','test')),
  program_id bigint REFERENCES public.iot_program_lumini(id), utilizator uuid REFERENCES public.profiles(id),
  ok boolean NOT NULL, eroare text, creat_la timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX iot_lumini_jurnal_timp ON public.iot_lumini_jurnal(creat_la DESC);
CREATE TABLE public.iot_lumini_setari (
  id boolean PRIMARY KEY DEFAULT true CHECK (id),
  lat numeric NOT NULL DEFAULT 44.94 CHECK (lat BETWEEN -65 AND 65),
  lon numeric NOT NULL DEFAULT 26.03 CHECK (lon BETWEEN -180 AND 180),
  tz text NOT NULL DEFAULT 'Europe/Bucharest' CHECK (tz='Europe/Bucharest'),
  vacanta_de date, vacanta_pana date, simulare_pana_la time NOT NULL DEFAULT '23:30',
  runtime jsonb NOT NULL DEFAULT '{}',
  CHECK ((vacanta_de IS NULL AND vacanta_pana IS NULL) OR (vacanta_de IS NOT NULL AND vacanta_pana IS NOT NULL AND vacanta_pana >= vacanta_de))
);
