AS $lumini_cron_20261113a$
DECLARE s text;
BEGIN
  SELECT decrypted_secret INTO s FROM vault.decrypted_secrets WHERE name='IOT_CRON_SECRET' LIMIT 1;
  IF s IS NULL OR s='' THEN RETURN; END IF;
  PERFORM net.http_post(url:='https://dxczwkbciseqniprspcu.supabase.co/functions/v1/tuya',headers:=jsonb_build_object('Content-Type','application/json','x-iot-secret',s),body:='{"actiune":"programe_tick"}'::jsonb,timeout_milliseconds:=90000);
END $lumini_cron_20261113a$;

