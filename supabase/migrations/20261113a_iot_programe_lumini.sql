-- Un singur punct de scriere UI. Nicio cale de a introduce aprobare sau runtime din JSON.
CREATE FUNCTION public.iot_lumini_salveaza(p_actiune text, p_date jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','pg_temp'
AS $lumini_salveaza_20261113a$
DECLARE v_id bigint; v_ids integer[]; v_tip text; v_p jsonb; v_r record; v_other record;
BEGIN
  IF NOT public.iot_lumini_drept(false) THEN RAISE EXCEPTION 'Fara drept de scriere Cladire' USING ERRCODE='42501'; END IF;
  PERFORM pg_advisory_xact_lock(hashtext('iot_lumini_config'));
  PERFORM 1 FROM public.iot_lumini_setari WHERE id=true FOR UPDATE;
  IF EXISTS(SELECT 1 FROM public.iot_lumini_setari WHERE id=true AND COALESCE((runtime->>'lease_pana')::timestamptz,'epoch')>clock_timestamp()) THEN RAISE EXCEPTION 'Comanda/tick in curs; reincercati'; END IF;
  IF p_actiune='program' THEN
    v_tip:=p_date->>'tip'; v_p:=COALESCE(p_date->'parametri','{}');
    IF v_tip IS NULL OR v_tip NOT IN ('solar','orar','simulare_prezenta') OR jsonb_typeof(v_p) IS DISTINCT FROM 'object' THEN RAISE EXCEPTION 'Tip/parametri invalizi'; END IF;
    IF EXISTS(SELECT 1 FROM jsonb_object_keys(v_p) k WHERE NOT (k=ANY(CASE v_tip
      WHEN 'solar' THEN ARRAY['offset_pornire','offset_oprire']
      WHEN 'orar' THEN ARRAY['pornire','oprire','zile']
      ELSE ARRAY['sfarsit','explicit'] END))) THEN RAISE EXCEPTION 'Cheie parametri necunoscuta'; END IF;
    IF v_tip='solar' AND EXISTS(SELECT 1 FROM jsonb_each(v_p) e WHERE jsonb_typeof(e.value)<>'number' OR NOT (e.value#>>'{}') ~ '^-?[0-9]+([.]0+)?$') THEN RAISE EXCEPTION 'Offset intreg necesar'; END IF;
    SELECT array_agg(DISTINCT x::integer) INTO v_ids FROM jsonb_array_elements_text(p_date->'dispozitive') x;
    IF v_ids IS NULL OR cardinality(v_ids)>6 OR EXISTS(SELECT 1 FROM unnest(v_ids) i LEFT JOIN public.iot_lumini l ON l.dispozitiv_id=i WHERE l.dispozitiv_id IS NULL OR NOT l.activ OR (v_tip='simulare_prezenta' AND l.rol='exterior') OR (v_tip='solar' AND l.rol='interior')) THEN RAISE EXCEPTION 'Lista lumini invalida'; END IF;
    IF v_tip='solar' AND (abs(COALESCE((v_p->>'offset_pornire')::numeric,0))>180 OR abs(COALESCE((v_p->>'offset_oprire')::numeric,0))>180) THEN RAISE EXCEPTION 'Offset maxim 180 minute'; END IF;
    IF v_tip='orar' THEN
      IF jsonb_typeof(v_p->'pornire') IS DISTINCT FROM 'string' OR jsonb_typeof(v_p->'oprire') IS DISTINCT FROM 'string' THEN RAISE EXCEPTION 'Ore text necesare'; END IF;
      IF NOT COALESCE(v_p->>'pornire','') ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' OR NOT COALESCE(v_p->>'oprire','') ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' THEN RAISE EXCEPTION 'Ore invalide'; END IF;
      IF jsonb_typeof(v_p->'zile') IS DISTINCT FROM 'array' THEN RAISE EXCEPTION 'Zile invalide'; END IF;
      IF jsonb_array_length(v_p->'zile') NOT BETWEEN 1 AND 7 OR EXISTS(SELECT 1 FROM jsonb_array_elements(v_p->'zile') z WHERE jsonb_typeof(z)<>'number' OR NOT (z#>>'{}') ~ '^[0-6]([.]0+)?$') THEN RAISE EXCEPTION 'Zile invalide'; END IF;
    END IF;
    IF v_tip='simulare_prezenta' AND v_p ? 'sfarsit' AND (jsonb_typeof(v_p->'sfarsit') IS DISTINCT FROM 'string' OR NOT (v_p->>'sfarsit') ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$') THEN RAISE EXCEPTION 'Ora sfarsit invalida'; END IF;
    IF v_p ? 'explicit' AND jsonb_typeof(v_p->'explicit')<>'boolean' THEN RAISE EXCEPTION 'Activare explicita invalida'; END IF;
    v_id:=(p_date->>'id')::bigint;
    IF v_id IS NULL THEN
      INSERT INTO public.iot_program_lumini(nume,tip,dispozitive,parametri,creat_de) VALUES(p_date->>'nume',v_tip,v_ids,v_p,auth.uid()) RETURNING id INTO v_id;
    ELSE
      UPDATE public.iot_program_lumini SET nume=p_date->>'nume',tip=v_tip,dispozitive=v_ids,parametri=v_p,activ=false,aprobat_de=NULL,aprobat_la=NULL WHERE id=v_id;
      IF NOT FOUND THEN RAISE EXCEPTION 'Program inexistent'; END IF;
    END IF;
  ELSIF p_actiune='aprobare' THEN
    IF NOT public.iot_lumini_drept(true) THEN RAISE EXCEPTION 'Doar owner' USING ERRCODE='42501'; END IF;
    v_id:=(p_date->>'id')::bigint;
    SELECT * INTO STRICT v_r FROM public.iot_program_lumini WHERE id=v_id FOR UPDATE;
    IF (p_date->>'activ')::boolean THEN
      IF EXISTS(SELECT 1 FROM public.iot_program_lumini WHERE id<>v_id AND activ AND dispozitive && v_r.dispozitive) THEN RAISE EXCEPTION 'Dispozitiv folosit de alt program activ'; END IF;
      IF EXISTS(SELECT 1 FROM public.iot_lumini WHERE dispozitiv_id=ANY(v_r.dispozitive) AND (NOT activ OR (v_r.tip='simulare_prezenta' AND rol='exterior') OR (v_r.tip='solar' AND rol='interior'))) THEN RAISE EXCEPTION 'Rol/activare invalida'; END IF;
    END IF;
    UPDATE public.iot_program_lumini SET activ=(p_date->>'activ')::boolean,aprobat_de=auth.uid(),aprobat_la=now() WHERE id=v_id;
  ELSIF p_actiune IN ('rol','setari') THEN
    IF NOT public.iot_lumini_drept(true) THEN RAISE EXCEPTION 'Doar owner' USING ERRCODE='42501'; END IF;
    IF p_actiune='rol' THEN
      UPDATE public.iot_lumini SET rol=p_date->>'rol' WHERE dispozitiv_id=(p_date->>'dispozitiv_id')::integer;
      IF NOT FOUND THEN RAISE EXCEPTION 'Lumina inexistenta'; END IF;
      UPDATE public.iot_program_lumini SET activ=false,aprobat_de=NULL,aprobat_la=NULL WHERE dispozitive @> ARRAY[(p_date->>'dispozitiv_id')::integer];
    ELSE
      UPDATE public.iot_lumini_setari SET lat=(p_date->>'lat')::numeric,lon=(p_date->>'lon')::numeric,vacanta_de=NULLIF(p_date->>'vacanta_de','')::date,vacanta_pana=NULLIF(p_date->>'vacanta_pana','')::date,simulare_pana_la=(p_date->>'simulare_pana_la')::time WHERE id=true;
      UPDATE public.iot_program_lumini SET activ=false,aprobat_de=NULL,aprobat_la=NULL WHERE id IS NOT NULL;
    END IF;
  ELSE RAISE EXCEPTION 'Actiune invalida'; END IF;
  RETURN jsonb_build_object('ok',true,'id',v_id);
END $lumini_salveaza_20261113a$;

-- Lease globala + rezervari atomice. Limita include esecuri si toate sursele.
CREATE FUNCTION public.iot_lumini_runtime(p_actiune text,p_token text,p_date jsonb DEFAULT '{}') RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','pg_temp'
AS $lumini_runtime_20261113a$
DECLARE r jsonb; stamps jsonb; n integer;
BEGIN
  SELECT runtime INTO r FROM public.iot_lumini_setari WHERE id=true FOR UPDATE;
  IF p_actiune='acquire' THEN
    IF COALESCE((r->>'lease_pana')::timestamptz,'epoch')>clock_timestamp() THEN RETURN jsonb_build_object('ok',false,'error','Comanda/tick deja in curs'); END IF;
    r:=r || jsonb_build_object('token',p_token,'lease_pana',clock_timestamp()+interval '4 minutes','tick_n',0);
  ELSE
    IF r->>'token' IS DISTINCT FROM p_token OR COALESCE((r->>'lease_pana')::timestamptz,'epoch')<=clock_timestamp() THEN RETURN jsonb_build_object('ok',false,'error','Lease expirata'); END IF;
    IF p_actiune='reserve' THEN
      SELECT COALESCE(jsonb_agg(x),'[]') INTO stamps FROM jsonb_array_elements(COALESCE(r->'rezervari','[]')) x WHERE (x#>>'{}')::timestamptz>clock_timestamp()-interval '1 hour';
      n:=COALESCE((r->>'tick_n')::integer,0);
      IF jsonb_array_length(stamps)>=40 OR n>=12 THEN
        PERFORM public.iot_alerta('error','Lumini sediu: plafon comenzi atins','Oprire comenzi automate/manuale: maxim 12 pe tick si 40 pe ora.');
        RETURN jsonb_build_object('ok',false,'error','Plafon comenzi atins');
      END IF;
      r:=r || jsonb_build_object('rezervari',stamps || to_jsonb(clock_timestamp()),'tick_n',n+1);
    ELSIF p_actiune='save' THEN
      r:=r || jsonb_build_object('programe',p_date);
    ELSIF p_actiune='release' THEN r:=r-'token'-'lease_pana';
    ELSE RAISE EXCEPTION 'Actiune invalida'; END IF;
  END IF;
  UPDATE public.iot_lumini_setari SET runtime=r WHERE id=true;
  RETURN jsonb_build_object('ok',true,'runtime',r);
END $lumini_runtime_20261113a$;

