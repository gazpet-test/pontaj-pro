CREATE TABLE public.eip_articole (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  denumire text NOT NULL UNIQUE CHECK (btrim(denumire) <> ''),
  familie text NOT NULL CHECK (familie IN ('incaltaminte','imbracaminte','reflectorizante','cap_fata','maini','alte')),
