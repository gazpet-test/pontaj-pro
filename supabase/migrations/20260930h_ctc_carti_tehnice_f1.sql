-- Acces CTC = can_access_ctc OR is_owner. Ștergerea unei cărți întregi = doar owner.
DO $$
DECLARE t text;
  acces constant text := '(auth.uid() IS NOT NULL AND EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND (p.is_owner OR p.can_access_ctc)))';
  owner constant text := '(auth.uid() IS NOT NULL AND EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.is_owner))';
BEGIN
  FOREACH t IN ARRAY ARRAY['ctc_templates','ctc_template_pozitii','ctc_carti','ctc_documente_carte'] LOOP
    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING %s', t||'_select', t, acces);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT TO authenticated WITH CHECK %s', t||'_insert', t, acces);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated USING %s WITH CHECK %s', t||'_update', t, acces, acces);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR DELETE TO authenticated USING %s', t||'_delete', t,
                   CASE WHEN t = 'ctc_carti' THEN owner ELSE acces END);
  END LOOP;
END $$;

-- ─── 6. View progres (checklist „47/93") ────────────────────────
CREATE VIEW public.v_ctc_carti_progres WITH (security_invoker = on) AS
SELECT c.id AS carte_id,
       count(d.id)                                                          AS total_pozitii,
       count(d.id) FILTER (WHERE d.status <> 'na')                           AS pozitii_aplicabile,
       count(d.id) FILTER (WHERE d.status IN ('incarcat','verificat'))       AS pozitii_incarcate,
       count(d.id) FILTER (WHERE d.status = 'verificat')                     AS pozitii_verificate,
       count(d.id) FILTER (WHERE d.status = 'lipsa' AND d.obligatoriu)       AS obligatorii_lipsa,
       coalesce(sum(d.nr_pagini) FILTER (WHERE d.status IN ('incarcat','verificat')), 0) AS total_pagini
FROM public.ctc_carti c
LEFT JOIN public.ctc_documente_carte d ON d.carte_id = c.id
GROUP BY c.id;
REVOKE ALL ON public.v_ctc_carti_progres FROM anon;
GRANT SELECT ON public.v_ctc_carti_progres TO authenticated, service_role;

