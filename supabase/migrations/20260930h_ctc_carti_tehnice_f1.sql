-- Decizii Răzvan 30.09.2026: Q1 A+C (schelet Transgaz generic acum, pozițiile reale extrase ulterior din cărțile
-- de pe NAS) · Q2 B (O SINGURĂ carte pe proiect) · Q3 B (poziție atașabilă din arhiva comenzilor furnizor, prin
-- referință, fără re-upload) · Q4 A (bucket ctc-documente, 50 MB/fișier, doar PDF — imaginile se convertesc
-- client-side, decizia „TOTUL PDF").
-- Acces: profiles.can_access_ctc OR profiles.is_owner (ca în spec). Ștergerea unei cărți: doar owner.
-- Tabela veche ctc_documente (goală, legată de comenzi) NU se atinge.
-- Obiecte noi: 4 tabele + 1 view (security_invoker) + bucket + policies. Fără funcții, fără edge functions.

-- ─── 1. Template-uri per beneficiar ─────────────────────────────
CREATE TABLE public.ctc_templates (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beneficiar_nume text NOT NULL,
  denumire        text NOT NULL,
  activ           boolean NOT NULL DEFAULT true,
  observatii      text,
  created_by      uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.ctc_templates IS '[CTC] Template carte tehnică per beneficiar (Transgaz, Distrigaz, Delgaz…). Checklist-ul stă în ctc_template_pozitii.';

CREATE TABLE public.ctc_template_pozitii (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id       bigint NOT NULL REFERENCES public.ctc_templates(id) ON DELETE CASCADE,
  categorie         text NOT NULL,
  denumire_document text NOT NULL,
  ordine            int  NOT NULL,
  obligatoriu       boolean NOT NULL DEFAULT true,
  observatii        text,
  created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ctc_template_pozitii_tpl_idx ON public.ctc_template_pozitii (template_id, ordine);
COMMENT ON TABLE public.ctc_template_pozitii IS '[CTC] Pozițiile (documentele cerute) ale unui template, în ordinea din borderou.';

-- ─── 2. Cărțile ─────────────────────────────────────────────────
CREATE TABLE public.ctc_carti (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proiect_id           bigint REFERENCES public.executie_proiecte(id) ON DELETE SET NULL,
  contract_id          bigint REFERENCES public.contracte_terti(id)   ON DELETE SET NULL,
  template_id          bigint REFERENCES public.ctc_templates(id)     ON DELETE SET NULL,
  beneficiar_nume      text,
  denumire_obiectiv    text NOT NULL,
  numar_contract       text,
  data_contract        date,
  localitate           text,
  judet                text,
  status               text NOT NULL DEFAULT 'in_lucru' CHECK (status IN ('in_lucru','completa','predata')),
  borderou_path        text,
  borderou_generat_at  timestamptz,
  pdf_final_path       text,          -- F2 (PDF unificat, Edge Function)
  pdf_final_generat_at timestamptz,   -- F2
  predat_la            date,
  predat_catre         text,
  pv_predare_path      text,
  observatii           text,
  created_by           uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ctc_carti_proiect_unic UNIQUE (proiect_id)   -- Q2 B: o singură carte pe proiect (NULL = lucrare fără proiect în Execuție)
);
COMMENT ON TABLE public.ctc_carti IS '[CTC] Cartea Tehnică a Construcției: dosarul de conformitate predat beneficiarului la recepție. 1 carte / proiect.';

-- ─── 3. Documentele unei cărți (checklist-ul concret) ───────────
CREATE TABLE public.ctc_documente_carte (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  carte_id            bigint NOT NULL REFERENCES public.ctc_carti(id) ON DELETE CASCADE,
  template_pozitie_id bigint REFERENCES public.ctc_template_pozitii(id) ON DELETE SET NULL,
  categorie           text NOT NULL,
  denumire_document   text NOT NULL,
  nr_pozitie          int,             -- numărul din borderou (se recalculează la generare)
  ordine              int NOT NULL,
  obligatoriu         boolean NOT NULL DEFAULT true,
  status              text NOT NULL DEFAULT 'lipsa' CHECK (status IN ('lipsa','incarcat','verificat','na')),
  -- fișierul: fie urcat în ctc-documente, fie referință la un document din arhiva comenzilor (Q3 B)
  sursa               text NOT NULL DEFAULT 'upload' CHECK (sursa IN ('upload','arhiva_comenzi')),
  fisier_bucket       text NOT NULL DEFAULT 'ctc-documente' CHECK (fisier_bucket IN ('ctc-documente','comenzi-furnizor')),
  fisier_path         text,
  fisier_nume         text,
  fisier_size_bytes   bigint,
  cfd_id              bigint REFERENCES public.comenzi_furnizor_documente(id) ON DELETE SET NULL,
  nr_pagini           int CHECK (nr_pagini IS NULL OR nr_pagini > 0),
  nr_pagina_start     int,
  nr_pagina_end       int,
  observatii          text,
  uploadat_de         uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  uploadat_la         timestamptz,
  verificat_de        uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  verificat_la        timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ctc_doc_sursa_coerenta CHECK (
    (sursa = 'upload' AND fisier_bucket = 'ctc-documente')
    OR (sursa = 'arhiva_comenzi' AND fisier_bucket = 'comenzi-furnizor')
  )
);
CREATE INDEX ctc_documente_carte_carte_idx ON public.ctc_documente_carte (carte_id, ordine);
CREATE INDEX ctc_documente_carte_cfd_idx   ON public.ctc_documente_carte (cfd_id) WHERE cfd_id IS NOT NULL;
COMMENT ON TABLE public.ctc_documente_carte IS '[CTC] Pozițiile concrete ale unei cărți (copiate din template la creare, editabile). Fișier propriu sau referință la comenzi_furnizor_documente.';

