-- Helperul si politicile ofertelor reproduc filtrarea comerciala reala.
CREATE FUNCTION public.fn_are_acces_ofertare() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public','pg_temp'
AS $pt_fixture_ofertare$
 SELECT auth.uid() IS NOT NULL AND (
   EXISTS(SELECT 1 FROM public.profiles WHERE id=auth.uid() AND is_owner) OR
   EXISTS(SELECT 1 FROM public.user_module_access WHERE profile_id=auth.uid() AND module='ofertare'));
$pt_fixture_ofertare$;
REVOKE ALL ON FUNCTION public.fn_are_acces_ofertare() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.fn_are_acces_ofertare() TO authenticated;
ALTER TABLE public.probe_oferte ENABLE ROW LEVEL SECURITY;
CREATE POLICY probe_oferte_rls_sel ON public.probe_oferte FOR SELECT TO authenticated USING(public.fn_are_acces_ofertare());
CREATE POLICY probe_oferte_rls_ins ON public.probe_oferte FOR INSERT TO authenticated WITH CHECK(public.fn_are_acces_ofertare());
GRANT SELECT,INSERT ON public.probe_oferte TO authenticated;
